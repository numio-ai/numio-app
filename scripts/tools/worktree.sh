#!/usr/bin/env bash
# Worktree isolation — per-worktree Compose project + host-port allocation.
#
# A single git checkout of numio-app can have several worktrees running in
# parallel (split-branch work). Each must get its own Postgres/Valkey/backend
# /frontend so one worktree's migrations or data don't clobber another's.
#
# This module:
#   1. Derives a stable COMPOSE_PROJECT_NAME from the worktree path so
#      containers, volumes, and networks are namespaced by Compose.
#   2. Allocates host ports. The first worktree to claim defaults (5432,
#      6379, 8000, 5173, 3000) keeps them; later worktrees pick free
#      ephemeral ports.
#   3. Persists the allocation in .numio/worktree.env so subsequent commands
#      in the same worktree hit the same containers.
#
# Sourced by numio-dev.sh. Depends on PROJECT_DIR and log_* from common.sh.

set -euo pipefail

WORKTREE_ENV_FILE="${PROJECT_DIR}/.numio/worktree.env"

# Defaults match the classic single-worktree behavior. Keep in sync with the
# ${VAR:-N} fallbacks in docker-compose.yml.
DEFAULT_POSTGRES_HOST_PORT=5432
DEFAULT_VALKEY_HOST_PORT=6379
DEFAULT_BACKEND_HOST_PORT=8000
DEFAULT_FRONTEND_DEV_PORT=5173
DEFAULT_FRONTEND_CONTAINER_PORT=3000

# Derive a stable project name from the worktree path.
# Format: numio-<dirname>-<6-char sha1 prefix>
# The hash makes it unique even when two worktrees share a basename.
_wt_derive_project_name() {
  local path="$1"
  local base
  base="$(basename "$path" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9' '-' | sed -e 's/-\{1,\}/-/g' -e 's/^-//' -e 's/-$//')"
  local hash
  hash="$(printf '%s' "$path" | shasum -a 1 | cut -c1-6)"
  echo "numio-${base:-app}-${hash}"
}

# Collect ports claimed by sibling worktrees' .numio/worktree.env files.
# A port may be "claimed but not yet listening" — e.g. worktree A allocated
# 8000 for its backend but has only started infra, so 8000 isn't bound yet.
# Without this, worktree B would happily grab 8000 too and collide later.
#
# Sibling worktrees are discovered via `git worktree list`; if that fails
# (not in a git checkout), we return nothing and fall back to listen-only
# checks — acceptable because the single-worktree case can't collide.
_wt_sibling_claimed_ports() {
  local me_abs
  me_abs="$(cd "$PROJECT_DIR" && pwd -P)"
  git -C "$PROJECT_DIR" worktree list --porcelain 2>/dev/null \
    | awk '$1 == "worktree" { print $2 }' \
    | while read -r wt; do
        # Skip self; resolve to real path so symlinked /tmp vs /private/tmp
        # don't trick us into reading our own file.
        local wt_abs
        wt_abs="$(cd "$wt" 2>/dev/null && pwd -P)" || continue
        [[ "$wt_abs" == "$me_abs" ]] && continue
        local f="$wt/.numio/worktree.env"
        [[ -f "$f" ]] || continue
        # Extract the numeric value of every *_PORT var in the file.
        awk -F= '/_PORT=/ { print $2 }' "$f"
      done
}

# True if a TCP port is free on localhost AND not claimed by any sibling
# worktree's persisted port map.
_wt_port_free() {
  local port="$1"
  if lsof -nP -iTCP:"$port" -sTCP:LISTEN >/dev/null 2>&1; then
    return 1
  fi
  local claimed
  claimed="$(_wt_sibling_claimed_ports)"
  if [[ -n "$claimed" ]] && echo "$claimed" | grep -qw "$port"; then
    return 1
  fi
  return 0
}

# Ask the kernel for a free ephemeral port.
_wt_allocate_free_port() {
  python3 - <<'PY'
import socket
s = socket.socket()
s.bind(("127.0.0.1", 0))
print(s.getsockname()[1])
s.close()
PY
}

# Keep the default port if it's free; otherwise allocate an ephemeral one.
_wt_pick_port() {
  local default="$1"
  if _wt_port_free "$default"; then
    echo "$default"
  else
    _wt_allocate_free_port
  fi
}

_wt_write_env_file() {
  local file="$1"
  mkdir -p "$(dirname "$file")"
  {
    echo "# Generated by numio-dev.sh. Delete this file to re-allocate ports."
    echo "COMPOSE_PROJECT_NAME=${COMPOSE_PROJECT_NAME}"
    echo "POSTGRES_HOST_PORT=${POSTGRES_HOST_PORT}"
    echo "VALKEY_HOST_PORT=${VALKEY_HOST_PORT}"
    echo "BACKEND_HOST_PORT=${BACKEND_HOST_PORT}"
    echo "FRONTEND_DEV_PORT=${FRONTEND_DEV_PORT}"
    echo "FRONTEND_CONTAINER_PORT=${FRONTEND_CONTAINER_PORT}"
  } > "$file"
}

# Load the worktree's env file (or initialize it on first use).
# After this call, the following vars are exported:
#   COMPOSE_PROJECT_NAME, POSTGRES_HOST_PORT, VALKEY_HOST_PORT,
#   BACKEND_HOST_PORT, FRONTEND_DEV_PORT, FRONTEND_CONTAINER_PORT
worktree_load_env() {
  if [[ -f "$WORKTREE_ENV_FILE" ]]; then
    # shellcheck disable=SC1090
    set -a
    source "$WORKTREE_ENV_FILE"
    set +a
    return 0
  fi

  export COMPOSE_PROJECT_NAME POSTGRES_HOST_PORT VALKEY_HOST_PORT \
         BACKEND_HOST_PORT FRONTEND_DEV_PORT FRONTEND_CONTAINER_PORT

  COMPOSE_PROJECT_NAME="$(_wt_derive_project_name "$PROJECT_DIR")"
  POSTGRES_HOST_PORT="$(_wt_pick_port "$DEFAULT_POSTGRES_HOST_PORT")"
  VALKEY_HOST_PORT="$(_wt_pick_port "$DEFAULT_VALKEY_HOST_PORT")"
  BACKEND_HOST_PORT="$(_wt_pick_port "$DEFAULT_BACKEND_HOST_PORT")"
  FRONTEND_DEV_PORT="$(_wt_pick_port "$DEFAULT_FRONTEND_DEV_PORT")"
  FRONTEND_CONTAINER_PORT="$(_wt_pick_port "$DEFAULT_FRONTEND_CONTAINER_PORT")"

  _wt_write_env_file "$WORKTREE_ENV_FILE"
  log_info "Worktree stack initialized: $WORKTREE_ENV_FILE"
  log_info "  project=${COMPOSE_PROJECT_NAME}"
  log_info "  ports: postgres=${POSTGRES_HOST_PORT} valkey=${VALKEY_HOST_PORT} backend=${BACKEND_HOST_PORT} frontend(dev)=${FRONTEND_DEV_PORT} frontend(container)=${FRONTEND_CONTAINER_PORT}"
}

# Print the worktree's project name and port map.
worktree_print_env() {
  worktree_load_env
  cat <<EOF
project:             ${COMPOSE_PROJECT_NAME}
postgres:            localhost:${POSTGRES_HOST_PORT}
valkey:              localhost:${VALKEY_HOST_PORT}
backend:             localhost:${BACKEND_HOST_PORT}
frontend (vite):     localhost:${FRONTEND_DEV_PORT}
frontend (compose):  localhost:${FRONTEND_CONTAINER_PORT}
env file:            ${WORKTREE_ENV_FILE}
EOF
}

# Emit DATABASE_URL / VALKEY_URL for the native backend, based on worktree ports.
worktree_database_url() {
  echo "postgresql+psycopg://numio:numio@localhost:${POSTGRES_HOST_PORT}/numio"
}

worktree_valkey_url() {
  echo "valkey://localhost:${VALKEY_HOST_PORT}"
}
